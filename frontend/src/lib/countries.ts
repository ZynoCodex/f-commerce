/** Country name for an ISO 3166-1 alpha-2 code. */
export function countryName(code: string): string | undefined {
  return NAME_BY_CODE.get(code);
}

/** Country name for an IANA timezone, or undefined when the zone is unknown. */
export function countryForTimeZone(timeZone: string): string | undefined {
  const code = TIMEZONE_COUNTRY[timeZone];
  return code ? countryName(code) : undefined;
}

/**
 * The zone to country code map, exposed so a test can hold it to the country
 * list. Every code must be one the picker can show.
 */
export function timezoneCountryMap(): Readonly<Record<string, string>> {
  return TIMEZONE_COUNTRY;
}

/**
 * The country of the device's timezone. This is a location hint from the
 * device settings, not a geolocation lookup, so UTC and unknown zones fall
 * back to the default country.
 */
export function browserCountry(): string {
  try {
    const timeZone = new Intl.DateTimeFormat().resolvedOptions().timeZone;
    return countryForTimeZone(timeZone) ?? DEFAULT_COUNTRY;
  } catch {
    return DEFAULT_COUNTRY;
  }
}
